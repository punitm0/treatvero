const bySlug = new Map(doctors.map((d) => [d.slug, d]));
if (bySlug.size !== doctors.length) throw new Error("Duplicate doctor slug in data/doctors.ts");
for (const d of doctors) {
  const h = getHospital(d.hospital);
  if (!h) throw new Error(`Doctor ${d.slug} lists unknown hospital ${d.hospital}`);
  const extra = d.specialties.filter((s) => !h.specialties.includes(s));
  if (extra.length) throw new Error(`Doctor ${d.slug}: ${extra.join(", ")} not listed for ${h.slug}`);
}

export function getDoctor(slug: string): Doctor | undefined {
  return bySlug.get(slug);
}

export function getDoctorsForHospital(hospitalSlug: string): Doctor[] {
  return doctors.filter((d) => d.hospital === hospitalSlug);
}

export function getDoctorsForTreatment(slug: TreatmentSlug, limit?: number): Doctor[] {
  return doctors.filter((d) => d.specialties.includes(slug)).slice(0, limit);
}

/** Colleagues at the same hospital sharing a specialty first, then the rest of the hospital's listed doctors. */
export function getRelatedDoctors(d: Doctor, limit = 3): Doctor[] {
  const shared = (o: Doctor) => o.specialties.filter((s) => d.specialties.includes(s)).length;
  return getDoctorsForHospital(d.hospital)
    .filter((o) => o.slug !== d.slug)
    .sort((a, b) => shared(b) - shared(a))
    .slice(0, limit);
}

/** "Dr. Ajay Kaul" → "AK", "Dr K K Saxena" → "KS" (titles skipped). */
export function doctorInitials(d: Doctor): string {
  const parts = d.name
    .replace(/\(.*?\)/g, "")
    .split(/\s+/)
    .filter((p) => p && !/^(dr|prof|col|maj|brig|lt)\.?$/i.test(p));
  return ((parts[0]?.[0] ?? "") + (parts.length > 1 ? parts.at(-1)![0] : "")).toUpperCase();
}
